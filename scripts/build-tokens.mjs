// Turns the design tokens into Tailwind theme variables.
// Sources: klinfits-handoff/design/tokens.json + tokens/extra.json
// Outputs: app/theme.css (Tailwind @theme) and tokens/resolved.json (read by lib/tokens.ts)
// Run: npm run tokens          (write)
//      npm run tokens -- --check (fail if the outputs are out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = (path) => JSON.parse(readFileSync(`${root}${path}`, 'utf8'));
const base = read('klinfits-handoff/design/tokens.json');
const extra = read('tokens/extra.json');

const ROOT_PX = 16;
const rem = (px) => `${+(px / ROOT_PX).toFixed(4)}rem`;
const pxToRem = (value) => (value.endsWith('px') ? rem(parseFloat(value)) : value);

// Grows linearly from min (at minViewport) to max (at maxViewport). The rem
// part keeps the size growing with browser zoom, unlike a vw-only clamp.
function fluid([min, max], [minViewport, maxViewport] = [extra.fluid.minViewport, extra.fluid.maxViewport]) {
  const slope = (max - min) / (maxViewport - minViewport);
  const intercept = min - slope * minViewport;
  return `clamp(${rem(min)}, ${rem(intercept)} + ${+(slope * 100).toFixed(4)}vw, ${rem(max)})`;
}

// Colours, resolving aliases such as "{black}".
const colorValues = Object.fromEntries(base.color.tokens.map((t) => [t.name, t.value]));
const colors = base.color.tokens.map((t) => {
  const alias = /^\{(.+)\}$/.exec(t.value);
  const value = alias ? colorValues[alias[1]] : t.value;
  if (!value) throw new Error(`Unknown colour alias ${t.value}`);
  return { name: t.name, value: value.toLowerCase(), usage: t.usage };
});

// Type styles: handoff styles first, then extras (overrides replace in place).
const types = base.type.groups.flatMap((group) =>
  group.styles.map((s) => ({ ...s, family: group.family, group: group.name, source: 'tokens.json' })),
);
for (const style of extra.type) {
  const index = types.findIndex((t) => t.name === style.name);
  if (index !== -1 && !style.override) throw new Error(`${style.name} exists in tokens.json; add "override": true`);
  if (index === -1 && style.override) throw new Error(`${style.name} overrides nothing in tokens.json`);
  const merged = { ...style, group: style.family === 'display' ? 'Display' : 'Text', source: 'extra.json' };
  delete merged.override;
  if (index === -1) types.push(merged);
  else types[index] = merged;
}
// Keep display styles together (stable sort), so new extras don't land after the text styles.
types.sort((a, b) => (a.group === b.group ? 0 : a.group === 'Display' ? -1 : 1));
for (const t of types) {
  t.cssSize = t.fluid ? fluid(t.fluid, t.fluidViewports) : pxToRem(t.fontSize);
  if (/vw/.test(t.cssSize) && !/rem \+ [\d.]+vw/.test(t.cssSize)) {
    throw new Error(`${t.name}: vw sizes must be rem-based clamps`);
  }
}

const families = Object.entries(base.type.families).map(([name, stack]) => {
  // The first family in each stack is the next/font variable set in app/fonts.ts.
  const [, ...fallbacks] = stack.split(',').map((s) => s.trim());
  const variable = { display: '--font-clash', sans: '--font-switzer' }[name];
  if (!variable) throw new Error(`No next/font variable for family ${name}`);
  return { name, value: [`var(${variable})`, ...fallbacks].join(', '), stack };
});

const spacing = base.spacing.tokens;
const radii = base.radius.tokens;
const containers = extra.container;

const line = (name, value) => `  ${name}: ${value};`;
const css = [
  '/* GENERATED by scripts/build-tokens.mjs from klinfits-handoff/design/tokens.json',
  ' * and tokens/extra.json. Do not edit by hand: change the JSON and run `npm run tokens`. */',
  '',
  '@theme static {',
  '  /* Brand colours only: Tailwind\'s default palette is removed. */',
  line('--color-*', 'initial'),
  ...colors.map((c) => line(`--color-${c.name}`, c.value)),
  '',
  '  /* Radii (rounded-tile, rounded-pill, ...). */',
  line('--radius-*', 'initial'),
  ...radii.map((r) => line(`--${r.name}`, r.value)),
  '',
  '  /* Flat brand: no shadows. */',
  line('--shadow-*', 'initial'),
  line('--inset-shadow-*', 'initial'),
  line('--drop-shadow-*', 'initial'),
  line('--text-shadow-*', 'initial'),
  '',
  '  /* Spacing: Tailwind\'s 4px steps already match space-1 … space-22 (p-4 = 16px). */',
  ...spacing.filter((s) => !/^space-\d+$/.test(s.name)).map((s) => line(`--spacing-${s.name.replace(/^space-/, '')}`, s.value)),
  '',
  '  /* Width caps (max-w-content, max-w-bar). */',
  ...containers.map((c) => line(`--container-${c.name}`, c.value)),
  '',
  '  /* Weights in use: 400, 500, 600. */',
  line('--font-weight-*', 'initial'),
  line('--font-weight-normal', '400'),
  line('--font-weight-medium', '500'),
  line('--font-weight-semibold', '600'),
  '',
  '  /* Type styles (text-body, text-display-hero, ...). Display styles also need font-display uppercase. */',
  line('--text-*', 'initial'),
  ...types.flatMap((t) => [
    line(`--text-${t.name}`, t.cssSize),
    line(`--text-${t.name}--line-height`, String(t.lineHeight)),
    line(`--text-${t.name}--font-weight`, String(t.fontWeight)),
    ...(t.letterSpacing ? [line(`--text-${t.name}--letter-spacing`, t.letterSpacing)] : []),
  ]),
  '}',
  '',
  '/* Families point at the next/font variables from app/fonts.ts. */',
  '@theme inline {',
  line('--font-*', 'initial'),
  ...families.map((f) => line(`--font-${f.name}`, f.value)),
  '}',
  '',
].join('\n');

const resolved = {
  $comment: 'GENERATED by scripts/build-tokens.mjs. Do not edit.',
  colors,
  types: types.map(({ name, group, family, cssSize, fontSize, fluid: range, lineHeight, fontWeight, letterSpacing, sample, usage, source }) => ({
    name, group, family, cssSize, fontSize: fontSize ?? null, fluid: range ?? null, lineHeight, fontWeight,
    letterSpacing: letterSpacing ?? null, sample, usage, source,
  })),
  families,
  spacing,
  radii,
  containers,
};
const json = `${JSON.stringify(resolved, null, 2)}\n`;

const outputs = [
  ['app/theme.css', css],
  ['tokens/resolved.json', json],
];
if (process.argv.includes('--check')) {
  const stale = outputs.filter(([path, content]) => {
    try {
      return readFileSync(`${root}${path}`, 'utf8') !== content;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`Out of date: ${stale.map(([p]) => p).join(', ')}. Run npm run tokens.`);
    process.exit(1);
  }
  console.log('Tokens up to date.');
} else {
  for (const [path, content] of outputs) writeFileSync(`${root}${path}`, content);
  console.log(`Wrote app/theme.css and tokens/resolved.json (${colors.length} colours, ${types.length} type styles).`);
}
